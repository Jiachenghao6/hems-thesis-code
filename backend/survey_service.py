"""
survey_service.py — persistence for the post-task questionnaire.

Storage is an append-only JSONL file, one line per submitted page. That shape is
deliberate:

  * A page is written the moment the participant leaves it, so a drop-out on page
    four still leaves pages one to three intact.
  * Append-only means a later write can never damage an earlier one, which matters
    because this file holds the study's dependent variables and there is no second
    copy of a participant's answers.
  * One line per page rather than per participant keeps writes small and atomic
    enough that a process restart mid-study cannot corrupt an existing record.

The same half-written-line hazard that bit the assignment ledger applies here: if a
previous write was cut off without its newline, the next append would silently glue
two records together and both would be lost at parse time. `_ensure_trailing_newline`
is the same guard, for the same reason.

**No Prolific ID is ever written to this file.** Responses carry only the anonymous
participant_id generated by session_service. The mapping from that id back to a
Prolific ID lives in the assignment ledger alone, so the response data can be shared,
archived or attached to the thesis without carrying an identifier that Prolific can
resolve to a person.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

from storage import data_file

SURVEY_FILE = data_file("survey_responses.jsonl")

#: Pages the frontend is allowed to submit. An unknown page name means the client
#: and the server have drifted apart — better to reject it loudly than to collect a
#: column nobody will know how to score later.
VALID_PAGES = {"demographics", "tlx", "tia_1", "tia_2", "checks"}


def _ensure_trailing_newline() -> None:
    """Append a newline if the file does not end with one.

    Guards against a previous write having been interrupted: without this, the next
    record would be concatenated onto the truncated line and both records would be
    unparseable.
    """
    if not SURVEY_FILE.exists() or SURVEY_FILE.stat().st_size == 0:
        return
    with SURVEY_FILE.open("rb+") as f:
        f.seek(-1, 2)
        if f.read(1) != b"\n":
            f.write(b"\n")


def record_page(participant_id: str, condition: str, page: str, answers: dict) -> dict:
    """Write one page of answers. Returns the stored record.

    Answers are stored exactly as the participant gave them. Reverse-coded items
    (TiA 5, 7, 10, 15, 16; NASA-TLX Performance) are recoded during analysis, not
    here — storing recoded values would make the raw responses unrecoverable if the
    scoring is ever revised, and would silently corrupt the data if this function
    were ever run twice on the same record.
    """
    if page not in VALID_PAGES:
        raise ValueError(f"Unknown survey page '{page}'. Valid: {sorted(VALID_PAGES)}")

    record = {
        "participant_id": participant_id,
        "condition": condition,
        "page": page,
        "answers": answers,
        "timestamp": datetime.now(timezone.utc).isoformat(),
    }

    _ensure_trailing_newline()
    with SURVEY_FILE.open("a", encoding="utf-8") as f:
        f.write(json.dumps(record, ensure_ascii=False) + "\n")
        f.flush()

    return record


def survey_summary() -> dict:
    """Researcher-facing progress counts. Never exposed to participants.

    Reports how many participants have completed each page, which is what tells you
    during data collection whether people are dropping out at a particular page —
    a long TiA page, say — rather than only finding out at analysis time.
    """
    if not SURVEY_FILE.exists():
        return {"records": 0, "by_page": {}, "complete_participants": 0}

    by_page: dict[str, set[str]] = {}
    total = 0
    with SURVEY_FILE.open(encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                # A damaged line is reported, not skipped in silence: the count of
                # readable records would otherwise look like the count of collected
                # ones, and data loss would go unnoticed until analysis.
                by_page.setdefault("__unparseable__", set()).add(f"line{total}")
                total += 1
                continue
            total += 1
            by_page.setdefault(rec.get("page", "?"), set()).add(rec.get("participant_id", "?"))

    finishers = by_page.get("checks", set())
    return {
        "records": total,
        "by_page": {k: len(v) for k, v in sorted(by_page.items())},
        "complete_participants": len(finishers),
    }
